package main

import (
	"fmt"
	"strings"

	annotation "github.com/lwbio/async/cmd/protoc-gen-go-async/async"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
)

const (
	contextPackage = protogen.GoImportPath("context")
	asyncPackage   = protogen.GoImportPath("github.com/lwbio/async")
	requestPackage = protogen.GoImportPath("github.com/lwbio/async/request")
)

func enabled(method *protogen.Method, requireAnnotation bool) bool {
	return !method.Desc.IsStreamingClient() && !method.Desc.IsStreamingServer() &&
		(!requireAnnotation || proto.GetExtension(method.Desc.Options(), annotation.E_Enable).(bool))
}

func generateFile(gen *protogen.Plugin, file *protogen.File, requireAnnotation bool) *protogen.GeneratedFile {
	anyEnabled := false
	for _, service := range file.Services {
		for _, method := range service.Methods {
			anyEnabled = anyEnabled || enabled(method, requireAnnotation)
		}
	}
	if !anyEnabled {
		return nil
	}
	g := gen.NewGeneratedFile(file.GeneratedFilenamePrefix+"_async.pb.go", file.GoImportPath)
	g.P("// Code generated by protoc-gen-go-async. DO NOT EDIT.")
	g.P("// versions:")
	g.P("// - protoc-gen-go-async ", release)
	g.P("// - protoc             ", protocVersion(gen))
	g.P("// source: ", file.Desc.Path())
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()
	g.P("// Compile-time references to the generated binding dependencies.")
	g.P("var _ = new(", contextPackage.Ident("Context"), ")")
	g.P("var _ = new(", asyncPackage.Ident("Runtime"), ")")
	g.P("var _ = new(", requestPackage.Ident("Client"), ")")
	for _, service := range file.Services {
		if service.Desc.Options().(*descriptorpb.ServiceOptions).GetDeprecated() {
			g.P("// Deprecated: Do not use.")
		}
		sd := serviceDesc{ServiceType: service.GoName, ServiceName: string(service.Desc.FullName())}
		for _, method := range service.Methods {
			if !enabled(method, requireAnnotation) {
				continue
			}
			sd.Methods = append(sd.Methods, &methodDesc{
				Name: method.GoName, OriginalName: string(method.Desc.Name()),
				Request: g.QualifiedGoIdent(method.Input.GoIdent), Reply: g.QualifiedGoIdent(method.Output.GoIdent),
				Comment: strings.TrimSpace(method.Comments.Leading.String()),
			})
		}
		if len(sd.Methods) > 0 {
			g.P(sd.execute())
		}
	}
	return g
}

func protocVersion(gen *protogen.Plugin) string {
	v := gen.Request.GetCompilerVersion()
	if v == nil {
		return "(unknown)"
	}
	return fmt.Sprintf("v%d.%d.%d", v.GetMajor(), v.GetMinor(), v.GetPatch())
}
