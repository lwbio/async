package main

import (
	"strings"
	"testing"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

func TestGeneratedClientRegistrationAndResultDecoder(t *testing.T) {
	d := &descriptorpb.FileDescriptorProto{Name: proto.String("sample.proto"), Package: proto.String("sample"), Syntax: proto.String("proto3"), Options: &descriptorpb.FileOptions{GoPackage: proto.String("example.com/sample;sample")}, MessageType: []*descriptorpb.DescriptorProto{{Name: proto.String("Input")}, {Name: proto.String("Output")}}, Service: []*descriptorpb.ServiceDescriptorProto{{Name: proto.String("Orders"), Method: []*descriptorpb.MethodDescriptorProto{{Name: proto.String("Create"), InputType: proto.String(".sample.Input"), OutputType: proto.String(".sample.Output")}}}}}
	gen, err := (protogen.Options{}).New(&pluginpb.CodeGeneratorRequest{ProtoFile: []*descriptorpb.FileDescriptorProto{d}, FileToGenerate: []string{"sample.proto"}})
	if err != nil {
		t.Fatal(err)
	}
	file := generateFile(gen, gen.Files[0], false)
	content, err := file.Content()
	if err != nil {
		t.Fatal(err)
	}
	for _, expected := range []string{"request.Register(r, AsyncOperationOrdersCreate, srv.Create", "func (c *OrdersAsyncClient) Create", "DecodeOrdersCreateResult", "request.DecodeResultFor[Output]"} {
		if !strings.Contains(string(content), expected) {
			t.Fatalf("missing %q in output", expected)
		}
	}
	if generateFile(gen, gen.Files[0], true) != nil {
		t.Fatal("unannotated service generated by default")
	}
}
